/** Dedup by (category, term): bank entries win, since they are tied to existing questions. */
function merge(lists: VocabEntry[][]): VocabEntry[] {
  const seen = new Set<string>();
  const out: VocabEntry[] = [];
  for (const e of lists.flat()) {
    const key = `${e.category}|${norm(e.term)}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(e);
  }
  return out;
}

export const VOCAB: VocabEntry[] = merge([fromBank, curatedWords, curatedAntonyms, curatedIdioms, connectors, grammar]);
export const VOCAB_BY_ID: Record<string, VocabEntry> = Object.fromEntries(VOCAB.map((e) => [e.id, e]));

// ---------------------------------------------------------------------------
// Practice questions for curated entries (bank entries already have theirs).
// Deterministic distractors: seeded by entry id, so a question id always
// renders the same way (review screens and the mistakes notebook stay stable).
// ---------------------------------------------------------------------------
const clusterOf = new Map(words.map(([term, , , , tag]) => [term, tag]));
const hashSeed = (s: string) => [...s].reduce((h, c) => Math.imul(h ^ c.charCodeAt(0), 16777619) >>> 0, 2166136261);

function pickDistractors(pool: string[], correct: string, seed: string, exclude: Set<string> = new Set()): string[] {
  const rng = createRng(hashSeed(seed));
  return shuffle(rng, [...new Set(pool)].filter((m) => m !== correct && !exclude.has(m))).slice(0, 3);
}

const inGlossary = new Set(VOCAB.map((e) => e.id));
const live = <T extends VocabEntry>(list: T[]) => list.filter((e) => inGlossary.has(e.id));

function wordQuestions(): Question[] {
  const all = live(curatedWords);
  return all.map((e) => {
    const tag = clusterOf.get(e.term);
    const blocked = new Set(all.filter((o) => tag && clusterOf.get(o.term) === tag).map((o) => o.meaning));
    // Same part of speech (verbs "לX" vs. the rest), so the form of an option never gives the answer away.
    const isVerb = (o: VocabEntry) => o.term.startsWith('ל') && o.meaning.startsWith('ל');
    const ds = pickDistractors(all.filter((o) => isVerb(o) === isVerb(e)).map((o) => o.meaning), e.meaning, e.id, blocked);
    return withShuffledChoices(
      { id: e.questionId!, section: 'hebrew', subtype: 'אוצר מילים מורחב', prompt: `מה פירוש המילה "${e.term}"?`, explanation: `${e.term} = ${e.meaning}.${e.example ? `\nדוגמה: ${e.example}` : ''}`, difficulty: e.level },
      { text: e.meaning }, ds.map((text) => ({ text })),
    );
  });
}

function antonymQuestions(): Question[] {
  const all = live(curatedAntonyms);
  // Both sides of every pair are candidate distractors, except the asked word itself.
  const pool = antonymPairs.flatMap(([a, b]) => [a, b]);
  const isVerb = (w: string) => w.startsWith('ל');
  return all.map((e) => {
    const ds = pickDistractors(pool.filter((w) => isVerb(w) === isVerb(e.term)), e.meaning, e.id, new Set([e.term]));
    return withShuffledChoices(
      { id: e.questionId!, section: 'hebrew', subtype: 'הפכים', prompt: `מהו ההפך של "${e.term}"?`, explanation: `${e.term} ↔ ${e.meaning}.`, difficulty: e.level },
      { text: e.meaning }, ds.map((text) => ({ text })),
    );
  });
}

/** Idioms with overlapping meanings: never distractors for each other. */
const IDIOM_CLUSTERS: string[][] = [
  ['ראש קטן', 'לצאת ידי חובה'],
  ['ללכת עם הראש בקיר', 'לטפס על עץ גבוה'],
  ['לא מצא את ידיו ורגליו', 'לאבד את הצפון'],
  ['ראש גדול', 'יצא מגדרו'],
  ['לשים מקל בגלגלים', 'אבן נגף'],
];

function idiomQuestions(): Question[] {
  const all = live(curatedIdioms);
  return all.map((e) => {
    const near = new Set(IDIOM_CLUSTERS.filter((c) => c.includes(e.term)).flat());
    const blocked = new Set(all.filter((o) => near.has(o.term)).map((o) => o.meaning));
    const ds = pickDistractors(all.map((o) => o.meaning), e.meaning, e.id, blocked);
    return withShuffledChoices(
      { id: e.questionId!, section: 'hebrew', subtype: 'ביטויים וניבים', prompt: `מה פירוש הביטוי "${e.term}"?`, explanation: `${e.term} = ${e.meaning}.${e.example ? `\nדוגמה: ${e.example}` : ''}`, difficulty: e.level },
      { text: e.meaning }, ds.map((text) => ({ text })),
    );
  });
}

/** Relations close enough that one must never be a distractor for the other. */
const CONFUSABLE: Record<string, string[]> = {
  ניגוד: ['ויתור', 'ביטול'], ויתור: ['ניגוד'], ביטול: ['ניגוד'],
  תוצאה: ['סיכום'], סיכום: ['תוצאה'], הסבר: ['דוגמה'], דוגמה: ['הסבר'],
};

function connectorQuestions(): Question[] {
  const all = live(connectors);
  const groups = [...new Set(all.map((e) => e.group!))];
  return all.map((e) => {
    // Example sentence with the connector blanked out would leak grammar cues; ask for its relation instead.
    const ds = pickDistractors(groups, e.group!, e.id, new Set(CONFUSABLE[e.group!] ?? []));
    return withShuffledChoices(
      { id: e.questionId!, section: 'hebrew', subtype: 'מילות קישור', prompt: `איזה יחס מביעה מילת הקישור "${e.term}"?\n${e.example ?? ''}`, explanation: `"${e.term}" = ${e.meaning}.`, difficulty: e.level },
      { text: e.group! }, ds.map((text) => ({ text })),
    );
  });
}

export const vocabQuestions: Question[] = [...wordQuestions(), ...antonymQuestions(), ...idiomQuestions(), ...connectorQuestions()];
